function formatTime(value: string | null): string {
  if (!value) return '-';
  return dayjs(value).format('HH:mm');
}

function parseTime(value: string | null): dayjs.Dayjs | null {
  if (!value) return null;
  return dayjs(value);
}

function calcMinutes(start: dayjs.Dayjs, end: dayjs.Dayjs): number {
  return end.diff(start, 'minute');
}

function minutesToHours(minutes: number): string {
  const h = Math.floor(minutes / 60);
  const m = minutes % 60;
  return `${h}h ${m.toString().padStart(2, '0')}m`;
}

function getWorkMinutes(entry: TimeEntry): number {
  const clockIn = parseTime(entry.clock_in);
  const clockOut = parseTime(entry.clock_out);
  if (!clockIn || !clockOut) return 0;
  let total = calcMinutes(clockIn, clockOut);
  const breakStart = parseTime(entry.break_start);
  const breakEnd = parseTime(entry.break_end);
  if (breakStart && breakEnd) {
    total -= calcMinutes(breakStart, breakEnd);
  }
  return Math.max(total, 0);
}

function getBreakMinutes(entry: TimeEntry): number {
  const breakStart = parseTime(entry.break_start);
  const breakEnd = parseTime(entry.break_end);
  if (!breakStart || !breakEnd) return 0;
  return Math.max(calcMinutes(breakStart, breakEnd), 0);
}

export function TimeReportPDF({ employeeName, companyName, entries, startDate, endDate, labels }: TimeReportPDFProps) {
  const l = {
    reportTitle: 'Time Report',
    date: 'Date',
    clockIn: 'Clock In',
    clockOut: 'Clock Out',
    breakStart: 'Break Start',
    breakEnd: 'Break End',
    totalWork: 'Total Work',
    totalBreak: 'Total Break',
    employee: 'Employee',
    period: 'Period',
    generatedBy: 'Generated by PlegoHR',
    total: 'Total',
    ...labels,
  };
  const totalWorkMinutes = entries.reduce((sum, e) => sum + getWorkMinutes(e), 0);
  const totalBreakMinutes = entries.reduce((sum, e) => sum + getBreakMinutes(e), 0);

  return (
    <Document>
      <Page size="A4" style={styles.page}>
        <View style={styles.header}>
          <Text style={styles.companyName}>{companyName}</Text>
          <Text style={styles.reportTitle}>{l.reportTitle}</Text>
          <Text style={styles.subtitle}>{l.employee}: {employeeName}</Text>
          <Text style={styles.subtitle}>
            {l.period}: {dayjs(startDate).format('MMM D, YYYY')} - {dayjs(endDate).format('MMM D, YYYY')}
          </Text>
        </View>

        <View style={styles.table}>
          <View style={styles.tableHeader}>
            <Text style={styles.cellDate}>{l.date}</Text>
            <Text style={styles.cellTime}>{l.clockIn}</Text>
            <Text style={styles.cellTime2}>{l.clockOut}</Text>
            <Text style={styles.cellBreakStart}>{l.breakStart}</Text>
            <Text style={styles.cellBreakEnd}>{l.breakEnd}</Text>
            <Text style={styles.cellTotalWork}>{l.totalWork}</Text>
            <Text style={styles.cellTotalBreak}>{l.totalBreak}</Text>
          </View>

          {entries.map((entry, i) => (
            <View key={i} style={i % 2 === 0 ? styles.tableRow : styles.tableRowAlt}>
              <Text style={styles.cellDate}>{dayjs(entry.date).format('MMM D, YYYY')}</Text>
              <Text style={styles.cellTime}>{formatTime(entry.clock_in)}</Text>
              <Text style={styles.cellTime2}>{formatTime(entry.clock_out)}</Text>
              <Text style={styles.cellBreakStart}>{formatTime(entry.break_start)}</Text>
              <Text style={styles.cellBreakEnd}>{formatTime(entry.break_end)}</Text>
              <Text style={styles.cellTotalWork}>{minutesToHours(getWorkMinutes(entry))}</Text>
              <Text style={styles.cellTotalBreak}>{minutesToHours(getBreakMinutes(entry))}</Text>
            </View>
          ))}

          <View style={styles.summary}>
            <Text style={styles.cellDate}>{l.total}</Text>
            <Text style={styles.cellTime}></Text>
            <Text style={styles.cellTime2}></Text>
            <Text style={styles.cellBreakStart}></Text>
            <Text style={styles.cellBreakEnd}></Text>
            <Text style={styles.cellTotalWork}>{minutesToHours(totalWorkMinutes)}</Text>
            <Text style={styles.cellTotalBreak}>{minutesToHours(totalBreakMinutes)}</Text>
          </View>
        </View>

        <Text style={styles.footer}>
          {l.generatedBy} — {dayjs().format('MMM D, YYYY HH:mm')}
        </Text>
      </Page>
    </Document>
  );
}
